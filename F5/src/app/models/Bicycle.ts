export class Bicycle {
  id: number;
  name: string;
  value: number;
  typeID: number;
  brandID: number;

  constructor(id: number, name: string, value: number, typeID: number, brandID: number) {
    this.id = id;
    this.name = name;
    this.value = value;
    this.typeID = typeID;
    this.brandID = brandID;
  }
}


